#!/bin/bash
## Builds netskope-cert-bundle.pem (Netskope tenant CA + Mozilla root bundle) from a
## netskope-cert.pem that sits next to this script. Non-interactive. macOS and Linux.
##
## Intended for the admin/packaging machine. Obtain the tenant CA yourself (Netskope UI, API,
## or a machine where the client config is not protected), save it as netskope-cert.pem next
## to this script, then run it. The output, netskope-cert-bundle.pem, is what
## silent_configure_tools_unix.sh deploys to endpoints (default /usr/local/netskope).
##
## Usage: ./build_cert_bundle_unix.sh [-d DIR] [-i INPUT] [-o OUTPUT] [-m MOZILLA_CACERT.PEM]
##   -d  directory with the input and receiving the output   (default: script directory)
##   -i  Netskope CA filename                                (default: netskope-cert.pem)
##   -o  bundle filename                                     (default: netskope-cert-bundle.pem)
##   -m  local Mozilla bundle to use instead of downloading  (offline packaging)
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INPUT_NAME="netskope-cert.pem"
OUTPUT_NAME="netskope-cert-bundle.pem"
MOZILLA_LOCAL=""
MOZILLA_URL="https://curl.se/ca/cacert.pem"
MOZILLA_MIN_CERTS=100   # cacert.pem carries ~140; far fewer means an error page / truncation

while getopts "d:i:o:m:h" opt; do
  case "$opt" in
    d) DIR="$OPTARG" ;;
    i) INPUT_NAME="$OPTARG" ;;
    o) OUTPUT_NAME="$OPTARG" ;;
    m) MOZILLA_LOCAL="$OPTARG" ;;
    *) sed -n '2,13p' "$0"; exit 2 ;;
  esac
done

die() { echo "Error: $*" >&2; exit 1; }
command -v openssl >/dev/null 2>&1 || die "openssl is required"

tmp_dir=$(mktemp -d)
trap 'rm -rf "$tmp_dir"' EXIT

# normalize_pem SRC DEST LABEL
# Extracts every CERTIFICATE block (ignores any surrounding text), strips CR, validates each
# block with openssl, and writes them to DEST with a guaranteed trailing newline per block.
# Prints the number of certificates.
normalize_pem() {
  local src=$1 dest=$2 label=$3 n i
  : > "$dest"
  tr -d '\r' < "$src" | awk -v d="$tmp_dir" -v lbl="$label" '
    /-----BEGIN CERTIFICATE-----/ { n++; f = sprintf("%s/%s.%04d", d, lbl, n); inblk = 1 }
    inblk { print > f }
    /-----END CERTIFICATE-----/ { if (inblk) close(f); inblk = 0 }
    END { print n + 0 > (d "/" lbl ".count") }'
  n=$(cat "$tmp_dir/$label.count")
  [ "$n" -gt 0 ] || die "$label has no PEM certificates: $src"
  for ((i = 1; i <= n; i++)); do
    local part; part=$(printf '%s/%s.%04d' "$tmp_dir" "$label" "$i")
    openssl x509 -in "$part" -noout 2>/dev/null || die "$label: certificate #$i is not valid"
    cat "$part" >> "$dest"
    [ -z "$(tail -c1 "$part")" ] || echo >> "$dest"
  done
  echo "$n"
}

input_path="$DIR/$INPUT_NAME"
output_path="$DIR/$OUTPUT_NAME"
[ -f "$input_path" ] || die "Input certificate not found: $input_path"

echo "Reading Netskope CA: $input_path"
ns_count=$(normalize_pem "$input_path" "$tmp_dir/ns.pem" ns)
echo "  $ns_count certificate(s)"

if [ -n "$MOZILLA_LOCAL" ]; then
  [ -f "$MOZILLA_LOCAL" ] || die "Mozilla bundle not found: $MOZILLA_LOCAL"
  moz_src="$MOZILLA_LOCAL"
else
  moz_src="$tmp_dir/cacert.download"
  echo "Downloading Mozilla CA bundle: $MOZILLA_URL"
  # Verify TLS first; only fall back to unverified when the host is behind SSL inspection
  # whose CA is not trusted yet (the very thing being built). Result is validated below.
  if ! curl --connect-timeout 30 --max-time 120 --fail --silent --show-error "$MOZILLA_URL" -o "$moz_src" 2>/dev/null; then
    echo "Warning: verified download failed; retrying without certificate verification." >&2
    curl -k --connect-timeout 30 --max-time 120 --fail --silent --show-error "$MOZILLA_URL" -o "$moz_src" \
      || die "could not download the Mozilla bundle (use -m with a local copy)"
  fi
fi
moz_count=$(normalize_pem "$moz_src" "$tmp_dir/moz.pem" moz)
[ "$moz_count" -ge "$MOZILLA_MIN_CERTS" ] || die "Mozilla bundle has only $moz_count certificates (expected >= $MOZILLA_MIN_CERTS)"
echo "  $moz_count certificate(s)"

# Atomic write: build next to the target, then rename. The count header tells
# silent_configure_tools_* which leading certs are the Netskope CA (used to check/merge
# existing CA bundles). PEM readers ignore text outside cert blocks.
{
  echo "# Netskope SSL inspection trust bundle: Netskope tenant CA + Mozilla roots"
  echo "# Generated by build_cert_bundle_unix.sh on $(date '+%Y-%m-%d %H:%M:%S')"
  echo "# netskope-cert-count: $ns_count"
  cat "$tmp_dir/ns.pem" "$tmp_dir/moz.pem"
} > "$output_path.tmp"
chmod 644 "$output_path.tmp"
mv -f "$output_path.tmp" "$output_path"

echo
echo "Bundle written: $output_path ($((ns_count + moz_count)) certificates: $ns_count Netskope + $moz_count Mozilla)"
